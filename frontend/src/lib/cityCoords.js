// Поиск координат города (без учёта регистра, частичное совпадение)
export const getCityCoords = (cityName) => {
    if (!cityName) return null;
    const normalized = cityName.trim().toLowerCase();

    // Точное совпадение
    const exactMatch = Object.keys(CITY_COORDS).find(
        city => city.toLowerCase() === normalized
    );
    if (exactMatch) return CITY_COORDS[exactMatch];

    // Частичное совпадение (для "Нижний Новгород" → "Нижний")
    const partialMatch = Object.keys(CITY_COORDS).find(
        city => city.toLowerCase().includes(normalized) || normalized.includes(city.toLowerCase())
    );
    if (partialMatch) return CITY_COORDS[partialMatch];

    return null;
};
